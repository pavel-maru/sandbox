#!/usr/bin/env python3
"""
Task: Demonstrate mutability of lists when passed to a function.
Run: python3 list_mutation_demo.py
Status: Done
"""


def mutate_list(lst: list) -> None:
    """
    Мутирует переданный список несколькими способами.

    В этой функции мы намеренно используем глобальный список для печати,
    чтобы показать, что изменения видны снаружи. Однако в реальном коде
    лучше использовать переданный аргумент и не обращаться к глобальным переменным.

    Args:
        lst: Список для мутации (передаётся по ссылке).
    """
    # 1. Добавляем элемент в конец (мутация)
    lst.append(5)
    print("После append(5):", lst)          # выведет [1, 2, 3, 5]

    # 2. Расширяем список самим собой.
    #    В Python при extend с тем же объектом сначала создаётся копия элементов,
    #    чтобы избежать бесконечного цикла. Поэтому список удвоится.
    lst.extend(lst)
    print("После extend(lst):", lst)        # выведет [1, 2, 3, 5, 1, 2, 3, 5]

    # 3. Изменяем элемент по индексу
    lst[0] = 0
    print("После lst[0] = 0:", lst)         # выведет [0, 2, 3, 5, 1, 2, 3, 5]

    # 4. Заменяем всё содержимое списка (с сохранением того же объекта)
    lst[:] = [7]
    print("После lst[:] = [7]:", lst)       # выведет [7]


def main() -> None:
    """Основная демонстрационная функция."""
    original = [1, 2, 3]
    print("Исходный список:", original)

    mutate_list(original)

    # После вызова функции список изменился, потому что мы мутировали тот же объект
    print("Список после вызова функции:", original)   # выведет [7]


if __name__ == "__main__":
    main()
